ServerEvents.recipes(event => {
  event
    .shaped(GRAFT_TABLE_ITEM, ['PPP', 'L L', 'LLL'], {
      L: '#minecraft:logs',
      P: '#minecraft:planks'
    })
    .id('kubejs:grafting_table');

  GRAFT_CROPS.concat(GRAFT_TREES).forEach(row =>
    cm.recipe('grafting/' + row[0], {
      machine: GRAFT_MACHINE,
      time: GRAFT_BASE_TIME,
      items: [
        [GRAFT_ID[row[1]], 1],
        [GRAFT_ID[row[2]], 1]
      ],
      slots: ['input_a', 'input_b'],
      tool: { in: GRAFT_KNIFE_TAG, damage: 1, slots: ['knife'] },
      out: [[GRAFT_ID[row[0]], 1]],
      outSlots: ['output']
    })
  );
});

CustomMachineryEvents.upgrades(event =>
  GRAFT_KNIVES.forEach(knife =>
    event
      .create(knife[0], 1)
      .machine(GRAFT_MACHINE)
      .modifier(CMRecipeModifierBuilder.mulInput('custommachinery:speed', knife[1]))
  )
);
